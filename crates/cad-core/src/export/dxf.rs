//! Minimal DXF (AutoCAD R2000 / AC1015) writer. Emits each contour as an
//! `LWPOLYLINE` (or a native `CIRCLE`/`ARC` where the primitive is known), which
//! LibreCAD, AutoCAD, Fusion and Inkscape all import.
//!
//! Entities are placed on named layers (effective layer = explicit `layer`, else
//! `role`, else `"0"`), and a `TABLES`→`LAYER` section declares each layer with
//! the conventional color for its role (cut=white/7, score=blue/5,
//! engrave=red/1), so a single DXF carries a multi-operation cutter job.

use crate::export::{role_color, Item};
use crate::geom2d::ContourKind;

pub fn to_dxf(items: &[Item], mm: f64) -> String {
    let mut out = String::new();
    // --- HEADER: declare version and drawing units (4 = mm) ---
    push(&mut out, 999, "generated by cad-assist");
    push(&mut out, 0, "SECTION");
    push(&mut out, 2, "HEADER");
    push(&mut out, 9, "$ACADVER");
    push(&mut out, 1, "AC1015");
    push(&mut out, 9, "$INSUNITS");
    push(&mut out, 70, "4");
    push(&mut out, 0, "ENDSEC");

    // --- TABLES: declare each distinct layer with its role color ---
    let mut layers: Vec<&str> = Vec::new();
    for it in items {
        let l = it.layer_name();
        if !layers.contains(&l) {
            layers.push(l);
        }
    }
    push(&mut out, 0, "SECTION");
    push(&mut out, 2, "TABLES");
    push(&mut out, 0, "TABLE");
    push(&mut out, 2, "LAYER");
    push(&mut out, 70, &layers.len().to_string());
    for layer in &layers {
        let role = items
            .iter()
            .find(|it| &it.layer_name() == layer)
            .and_then(|it| it.role);
        let (_, aci) = role_color(role);
        push(&mut out, 0, "LAYER");
        push(&mut out, 2, layer);
        push(&mut out, 70, "0");
        push(&mut out, 62, &aci.to_string());
        push(&mut out, 6, "CONTINUOUS");
    }
    push(&mut out, 0, "ENDTAB");
    push(&mut out, 0, "ENDSEC");

    // --- ENTITIES ---
    push(&mut out, 0, "SECTION");
    push(&mut out, 2, "ENTITIES");
    for it in items {
        let layer = it.layer_name();
        for c in &it.shape.contours {
            match &c.kind {
                // A known circle primitive round-trips as a true CIRCLE entity.
                ContourKind::Circle { c: center, r } => {
                    push(&mut out, 0, "CIRCLE");
                    push(&mut out, 8, layer);
                    push(&mut out, 10, &format!("{:.6}", center.x * mm));
                    push(&mut out, 20, &format!("{:.6}", center.y * mm));
                    push(&mut out, 40, &format!("{:.6}", *r * mm));
                }
                // A known arc primitive round-trips as an ARC entity. DXF arcs are
                // CCW from start (50) to end (51); normalize so end > start.
                ContourKind::Arc {
                    c: center,
                    r,
                    a0,
                    a1,
                } => {
                    let start = *a0;
                    let mut end = *a1;
                    while end <= start {
                        end += 360.0;
                    }
                    push(&mut out, 0, "ARC");
                    push(&mut out, 8, layer);
                    push(&mut out, 10, &format!("{:.6}", center.x * mm));
                    push(&mut out, 20, &format!("{:.6}", center.y * mm));
                    push(&mut out, 40, &format!("{:.6}", *r * mm));
                    push(&mut out, 50, &format!("{start:.6}"));
                    push(&mut out, 51, &format!("{end:.6}"));
                }
                // Everything else keeps the tessellated LWPOLYLINE path.
                ContourKind::Polyline => {
                    if c.points.len() < 2 {
                        continue;
                    }
                    push(&mut out, 0, "LWPOLYLINE");
                    push(&mut out, 8, layer);
                    push(&mut out, 90, &c.points.len().to_string());
                    push(&mut out, 70, if c.closed { "1" } else { "0" });
                    for p in &c.points {
                        push(&mut out, 10, &format!("{:.6}", p.x * mm));
                        push(&mut out, 20, &format!("{:.6}", p.y * mm));
                    }
                }
            }
        }
    }
    push(&mut out, 0, "ENDSEC");
    push(&mut out, 0, "EOF");
    out
}

/// Append a DXF group: code on one line, value on the next.
fn push(out: &mut String, code: i32, value: &str) {
    out.push_str(&format!("{code}\n{value}\n"));
}
