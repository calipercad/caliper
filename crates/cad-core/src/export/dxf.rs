//! Minimal DXF (AutoCAD R2000 / AC1015) writer. Emits each contour as an
//! `LWPOLYLINE`, which LibreCAD, AutoCAD, Fusion and Inkscape all import.

use crate::geom2d::Shape;

pub fn to_dxf(shapes: &[(&str, &Shape)], mm: f64) -> String {
    let mut out = String::new();
    // --- HEADER: declare version and drawing units (4 = mm) ---
    push(&mut out, 999, "generated by cad-assist");
    push(&mut out, 0, "SECTION");
    push(&mut out, 2, "HEADER");
    push(&mut out, 9, "$ACADVER");
    push(&mut out, 1, "AC1015");
    push(&mut out, 9, "$INSUNITS");
    push(&mut out, 70, "4");
    push(&mut out, 0, "ENDSEC");

    // --- ENTITIES ---
    push(&mut out, 0, "SECTION");
    push(&mut out, 2, "ENTITIES");
    for (_, s) in shapes {
        for c in &s.contours {
            if c.points.len() < 2 {
                continue;
            }
            push(&mut out, 0, "LWPOLYLINE");
            push(&mut out, 8, "0"); // layer
            push(&mut out, 90, &c.points.len().to_string());
            push(&mut out, 70, if c.closed { "1" } else { "0" });
            for p in &c.points {
                push(&mut out, 10, &format!("{:.6}", p.x * mm));
                push(&mut out, 20, &format!("{:.6}", p.y * mm));
            }
        }
    }
    push(&mut out, 0, "ENDSEC");
    push(&mut out, 0, "EOF");
    out
}

/// Append a DXF group: code on one line, value on the next.
fn push(out: &mut String, code: i32, value: &str) {
    out.push_str(&format!("{code}\n{value}\n"));
}
