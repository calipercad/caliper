//! Wavefront OBJ writer. Emits one group per mesh; faces are 1-indexed.

use crate::geom3d::Mesh;

pub fn to_obj(meshes: &[(&str, &Mesh)], mm: f64) -> String {
    let mut out = String::new();
    out.push_str("# generated by Caliper\n");
    let mut base = 1usize; // OBJ indices are 1-based and global
    for (name, mesh) in meshes {
        out.push_str(&format!("o {}\n", name));
        for v in &mesh.verts {
            let v = *v * mm;
            out.push_str(&format!("v {:.6} {:.6} {:.6}\n", v.x, v.y, v.z));
        }
        for t in &mesh.tris {
            out.push_str(&format!(
                "f {} {} {}\n",
                t[0] + base,
                t[1] + base,
                t[2] + base
            ));
        }
        base += mesh.verts.len();
    }
    out
}
