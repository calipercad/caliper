//! SVG writer — the lingua franca for Cricut, Silhouette, laser cutters and
//! vinyl plotters. Emits real millimetre dimensions with matching viewBox and
//! one `<path>` per contour (fill:none, thin stroke = cut lines).

use crate::bbox::Aabb2;
use crate::geom2d::Shape;

pub fn to_svg(shapes: &[(&str, &Shape)], mm: f64) -> String {
    // Combined bounds (in mm), with a small margin.
    let mut b = Aabb2::empty();
    for (_, s) in shapes {
        let sb = s.bbox();
        if !sb.is_empty() {
            b.expand(sb.min);
            b.expand(sb.max);
        }
    }
    if b.is_empty() {
        b = Aabb2 {
            min: crate::math::Vec2::ZERO,
            max: crate::math::Vec2::new(1.0, 1.0),
        };
    }
    let margin = 5.0 / mm; // ~5mm margin in scene units
    let minx = b.min.x - margin;
    let miny = b.min.y - margin;
    let w = b.width() + 2.0 * margin;
    let h = b.height() + 2.0 * margin;

    let wmm = w * mm;
    let hmm = h * mm;

    let mut out = String::new();
    out.push_str(&format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
         <svg xmlns=\"http://www.w3.org/2000/svg\" version=\"1.1\" \
         width=\"{wmm:.3}mm\" height=\"{hmm:.3}mm\" \
         viewBox=\"0 0 {wmm:.3} {hmm:.3}\">\n"
    ));
    out.push_str("  <!-- generated by cad-assist -->\n");

    // SVG y grows downward; flip so our +Y is up.
    let map = |p: crate::math::Vec2| -> (f64, f64) {
        let x = (p.x - minx) * mm;
        let y = (h - (p.y - miny)) * mm;
        (x, y)
    };

    for (name, s) in shapes {
        out.push_str(&format!("  <g id=\"{}\">\n", xml_escape(name)));
        for c in &s.contours {
            if c.points.is_empty() {
                continue;
            }
            let mut d = String::new();
            for (i, &p) in c.points.iter().enumerate() {
                let (x, y) = map(p);
                d.push_str(&format!("{}{x:.4} {y:.4}", if i == 0 { "M" } else { " L" }));
            }
            if c.closed {
                d.push_str(" Z");
            }
            out.push_str(&format!(
                "    <path d=\"{d}\" fill=\"none\" stroke=\"black\" stroke-width=\"0.2\"/>\n"
            ));
        }
        out.push_str("  </g>\n");
    }
    out.push_str("</svg>\n");
    out
}

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}
