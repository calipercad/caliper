//! Basic G-code writer for pen plotters, drag-knife cutters and laser/CNC
//! contour cutting. Traces each contour with the tool down, lifting between
//! contours. Not a full CAM post — a clean, honest starting point.

use crate::geom2d::Shape;

pub struct GcodeOptions {
    pub feed: f64,      // cutting feed rate (mm/min)
    pub travel: f64,    // rapid feed rate (mm/min)
    pub z_up: f64,      // safe/travel height (mm)
    pub z_down: f64,    // cutting depth (mm)
    pub spindle: bool,  // emit M3/M5 (spindle/laser on-off)
}

impl Default for GcodeOptions {
    fn default() -> Self {
        GcodeOptions {
            feed: 800.0,
            travel: 2000.0,
            z_up: 5.0,
            z_down: -1.0,
            spindle: false,
        }
    }
}

pub fn to_gcode(shapes: &[(&str, &Shape)], mm: f64, opt: &GcodeOptions) -> String {
    let mut g = String::new();
    g.push_str("; generated by cad-assist\n");
    g.push_str("G21 ; mm\nG90 ; absolute\n");
    g.push_str(&format!("G0 Z{:.3}\n", opt.z_up));
    if opt.spindle {
        g.push_str("M3 S1000\n");
    }

    for (name, s) in shapes {
        g.push_str(&format!("; contour group: {name}\n"));
        for c in &s.contours {
            if c.points.is_empty() {
                continue;
            }
            let first = c.points[0];
            g.push_str(&format!(
                "G0 X{:.3} Y{:.3} F{:.0}\n",
                first.x * mm,
                first.y * mm,
                opt.travel
            ));
            g.push_str(&format!("G1 Z{:.3} F{:.0}\n", opt.z_down, opt.feed));
            for p in c.points.iter().skip(1) {
                g.push_str(&format!("G1 X{:.3} Y{:.3}\n", p.x * mm, p.y * mm));
            }
            if c.closed {
                g.push_str(&format!("G1 X{:.3} Y{:.3}\n", first.x * mm, first.y * mm));
            }
            g.push_str(&format!("G0 Z{:.3}\n", opt.z_up));
        }
    }

    if opt.spindle {
        g.push_str("M5\n");
    }
    g.push_str("G0 X0 Y0\nM2 ; end\n");
    g
}
